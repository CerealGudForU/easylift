// Runs after `expo export -p web`. Writes two files into dist/:
//   sw.js     the service worker: precaches the whole app so it opens with no connection
//   _headers  Cloudflare response headers: caching rules and the Content Security Policy
//
// Usage: node scripts/build-sw.mjs   (or `npm run build:web`, which exports first)
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';
if (!existsSync(join(DIST, 'index.html'))) {
  throw new Error('dist/index.html not found: run `npx expo export -p web` first.');
}

// The Supabase URL comes from the build environment (Cloudflare build settings), or
// .env.local when building on this PC.
if (!process.env.EXPO_PUBLIC_SUPABASE_URL && existsSync('.env.local')) process.loadEnvFile('.env.local');
const supabaseUrl = process.env.EXPO_PUBLIC_SUPABASE_URL;
if (!supabaseUrl) throw new Error('EXPO_PUBLIC_SUPABASE_URL is not set.');
const supabase = new URL(supabaseUrl);

// Files the service worker must not precache: itself, Cloudflare config, build metadata.
const SKIP = new Set(['sw.js', '_headers', '_redirects', 'metadata.json']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(DIST)
  .map((path) => ({ path, rel: relative(DIST, path).split(sep).join('/') }))
  .filter(({ rel }) => !SKIP.has(rel) && !rel.endsWith('.map'))
  .sort((a, b) => a.rel.localeCompare(b.rel));

// The version changes whenever any file does, which makes browsers install the new worker.
const hash = createHash('sha256');
for (const { rel, path } of files) hash.update(rel).update(readFileSync(path));
const version = hash.digest('hex').slice(0, 12);

// index.html is cached as "/" (Cloudflare redirects /index.html to /, and Safari refuses
// redirected responses for page loads).
const urls = files.map(({ rel }) => (rel === 'index.html' ? '/' : `/${encodeURI(rel)}`));
const bytes = files.reduce((n, { path }) => n + statSync(path).size, 0);

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'easylift-' + VERSION;
const PRECACHE = ${JSON.stringify(urls, null, 2)};

// Download the whole app. A new version waits until the app asks it to take over
// (the "New version" banner), so it never swaps code in the middle of a workout.
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE.map((url) => new Request(url, { cache: 'reload' })))),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

// Drop older versions' caches and take control of open pages right away.
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('easylift-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  // Supabase and anything else off-site go straight to the network.
  if (url.origin !== self.location.origin) return;

  // Every page is the same single-page app: serve the cached shell, so the app opens
  // instantly and with no connection.
  if (request.mode === 'navigate') {
    event.respondWith(
      caches
        .open(CACHE)
        .then((cache) => cache.match('/'))
        .then((shell) => shell || fetch(request)),
    );
    return;
  }

  // Files are named by their content hash, so a cached copy is always correct.
  event.respondWith(
    caches.open(CACHE).then((cache) =>
      cache.match(request).then(
        (hit) =>
          hit ||
          fetch(request).then((response) => {
            if (response.ok && (url.pathname.startsWith('/_expo/') || url.pathname.startsWith('/assets/'))) {
              cache.put(request, response.clone());
            }
            return response;
          }),
      ),
    ),
  );
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);

const csp = [
  "default-src 'self'",
  "script-src 'self'",
  // react-native-web writes its styles into <style> tags at runtime.
  "style-src 'self' 'unsafe-inline'",
  `img-src 'self' data: blob: ${supabase.origin}`,
  "font-src 'self' data:",
  // blob:/data: for photos being resized and uploaded; wss: for live notifications.
  `connect-src 'self' blob: data: ${supabase.origin} wss://${supabase.host}`,
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

const headers = `# Generated by scripts/build-sw.mjs. Do not edit.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(), microphone=(), payment=()

# Always check for a new version of the app.
/
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
/sw.js
  Cache-Control: no-cache
/manifest.webmanifest
  Cache-Control: no-cache

# Content-hashed files never change.
/_expo/static/*
  Cache-Control: public, max-age=31536000, immutable
/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;
writeFileSync(join(DIST, '_headers'), headers);

console.log(`sw.js: version ${version}, ${urls.length} files, ${(bytes / 1024 / 1024).toFixed(1)} MB precached`);
console.log('_headers: written');
